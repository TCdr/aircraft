export const EwdMessageCodeOrder = new Map([...EwdMessages.keys()].map((code, index) => [code, index]));

export const getEwdMessageGroup = (code: string): string | undefined => EwdMessages.get(code)?.group;

export const getEwdGroupTitleCode = (group: string): string => EwdGroupTitles.get(group)!.code;

export const isEwdSpecialLineCode = (code: string): boolean => !!EwdMessages.get(code)?.specialLine;

export const isEwdSecondaryFailureCode = (code: string): boolean => !!EwdMessages.get(code)?.secondaryFailure;

// eslint-disable-next-line no-control-regex
const getVisibleTextWidth = (text: string) => text.replace(/\x1b[^m]*m/g, '').length;
// eslint-disable-next-line no-control-regex
const getLeadingColorControl = (text: string) => text.match(/\x1b<\dm/)?.[0] ?? '';

export const formatEwdMessages = (codes: string[]): string[] => {
  let previousGroup: string | undefined;

  return codes.map((code) => {
    const message = EwdMessages.get(code);

    if (message === undefined) {
      previousGroup = undefined;
      return '';
    }

    if (message.group === undefined) {
      return message.text;
    }

    const prefix =
      previousGroup === message.group
        ? `${getLeadingColorControl(EwdGroups[message.group])}${' '.repeat(getVisibleTextWidth(EwdGroups[message.group]))}`
        : EwdGroups[message.group];

    previousGroup = message.group;

    return `${prefix}${message.text}`;
  });
};
